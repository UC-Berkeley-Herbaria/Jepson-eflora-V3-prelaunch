Each
entry in ICPN includes the scientific name with author citation, the
family in which the taxon is included according to classification
adopted by the Jepson Flora Project (i.e., that used in
<i>The Jepson Manual</i>,
as updated by advances made in plant systematics
subsequently), an
&ldquo;Initial Editorial Analysis,&rdquo;
and an
&ldquo;Editorial Summary and Current Status.&rdquo;
Most names in ICPN come directly from
<i>The Jepson Manual</i>,
and for the majority of these no changes have been
proposed.  For these, the
&ldquo;Initial Editorial Analysis&rdquo;
consists of
nothing more than an indication that the
&ldquo;Source of the Report for California&rdquo;
is
<i>The Jepson Manual</i>.
Under
&ldquo;Editorial Summary and Current Status,&rdquo;
such cases include an indication of Current Status (e.g.,
JFP-1, accepted name for taxon native to California; JFP-2a,
taxonomic or nomenclatural synonym for taxon naturalized in
California; etc.), and an indication of the
&ldquo;Current Status Authority&rdquo;
(<i>The Jepson Manual</i>).  Each entry in ICPN also includes links to the
International Plant Name Index (IPNI; The Plant Names Project, 1999)
and Tropicos (Missouri Botanical Garden); some include links to
various external websites, as appropriate, including the CNPS Rare
Plant Inventory, the WEEDS database, Flora of North America North of
Mexico, Volume 3 (Nixon &amp; Muller, 1997), and various monographic
websites (e.g., Barbara Ertter's &ldquo;Native California Roses&rdquo;).		</td>
