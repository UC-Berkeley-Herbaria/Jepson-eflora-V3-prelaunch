Entries
for names that have come into use, or that have come back into use,
subsequent to
<i>The Jepson Manual</i>
(names that ultimately may or may not
represent changes relative to
<i>The Jepson Manual</i>), are fewer in
number, but each one is more extensive.  In these entries, the
&ldquo;Initial Editorial Analysis&rdquo;
includes
&ldquo;Source of Report for California,&rdquo;
as well as, under
&ldquo;Initial Editorial Comments,&rdquo;
a statement about how
or if the name was used in one or more of the various treatments of
the flora of California (e.g., Hickman, 1993; Kartesz &amp; Meacham,
1999; Munz, 1959, 1968).  Under
&ldquo;Editorial Summary and Current Status,&rdquo;
&ldquo;Editorial Summary&rdquo;
is an attempt to summarize, in a more or less
standardized way, whether the name is or is likely to be accepted or
rejected as a name representing a native or naturalized plant in
California (i.e., as part of the flora), followed by a statement
summarizing the status of the name relative to
<i>The Jepson Manual</i>
(e.g., addition, for taxon described since TJM; possible addition,
minor variant in TJM; probable rejection, infraspecific taxa not
recognized in TJM). 
&ldquo;Editorial Summary&rdquo;
is an attempt to provide users
with a quick way to put the name in context relative to
<i>The Jepson Manual</i>, and allows us to compute estimates of the kinds and numbers
of changes that have been proposed or confirmed since
<i>The Jepson Manual</i>.		</td>
