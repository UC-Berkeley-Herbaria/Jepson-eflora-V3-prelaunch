    <td class="bodyText">
		
Some
of the changes that have been proposed or confirmed since
<i>The Jepson Manual</i> result from changes in taxonomic philosophy, either on the
part of individual specialists regarding their particular group or
groups, or on the part of the Editors of the Jepson Flora Project
regarding plant systematics and the flora of California as a whole. 
Refinements in philosophy have been
adopted in light of the importance of floristic information to the
management of biodiversity in California, as such information is
gathered and managed at UC/JEPS; one of these refinements has to do
with ever changing ideas about the relationship between evolution and
classification in plants.  Opinions do and probably always will vary
on this subject, but an attempt is being made within the Jepson Flora
Project to recognized only groups in which all members have evolved
from a single, common ancestor (i.e., to recognize only monophyletic
groups), insofar as is practical and to the extent that data bearing
on this matter are available.  Such a philosophy is in keeping with
modern systematic practice as well as with the needs of society for
classifications that are predictive; that is, that allow us to
predict or suspect characteristics (e.g., medicinal uses) of a plant
by understanding its true, genetic, evolutionary relationships.  This
criterion for recognition of taxonomic groups is not new, and it was
certainly applied to some extent in <i>The Jepson Manual</i>.  What is new
is the extent to which it now is being applied in the classifications
we employ.		</td>
