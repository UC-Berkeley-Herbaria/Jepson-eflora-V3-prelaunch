<strong>The Index to California Plant Names (ICPN) includes names from a variety of sources (e.g., specimens, checklists, floras) that have been applied, correctly or incorrectly, to California plants.  Approximately 9,400 of 15,000 names presently included in ICPN appeared in The Jepson Manual as accepted names, names of minor variants, or synonyms; most of the remainder have come into use, or come back into use, correctly or incorrectly, since The Jepson Manual.</strong> The primary intention is to account for names people are likely to encounter, from whatever source, and to summarize the status of such names with respect to the first printing of The Jepson Manual (TJM), and to the flora of California as it is understood presently by authors contributing to the Second Edition of The Jepson Manual (to the extent that we are incorporating any changes these authors make relative to TJM as we become aware of them). New names for taxa already known to occur in the state, reports of taxa previously known to science but not known from California, the publication of names for taxa new to science, and many other kinds of changes or potential changes appear in the literature of botany much more frequently than floras are published, or even more frequently than updated floristic treatments appear online. Activity that has the potential to change the list of accepted names for plants occurring outside of cultivation in California appears in the Index to California Plant Names as soon as we become aware of it, so that ICPN is as current as any such comprehensive resource can be. Decisions whether or not to accept the potential changes to this list are made by the authors contributing to the Second Edition of The Jepson Manual.</span>	</td>
