The
entries in ICPN for 
<a href="/cgi-bin/get_cpn.pl?Constancea+nevinii&expand=1">
<i>Constancea nevinii</i>
(A. Gray) B. G. Baldwin</a>
and
<a href="/cgi-bin/get_cpn.pl?Eriophyllum+nevinii&expand=1">
<i>Eriophyllum nevinii</i> A. Gray</a>
are examples of
changes that have been confirmed since <i>The Jepson Manual</i>, and that
have resulted at least in part from this increased emphasis on
monophyly.  In short, investigations by Baldwin (1999) indicate that
not all species included in
<i>Eriophyllum</i> in <i>The Jepson Manual</i> evolved
from a single, common ancestor (i.e., that <i>Eriophyllum</i> as
circumscribed in <i>The Jepson Manual</i> is polyphyletic).  In particular,
phylogenetic analyses of evidence from morphology, cytology, and
ribosomal DNA indicate that
<i>Eriophyllum nevinii</i>
appears to be the
sole representative of a lineage that diverged from related genera
long ago, and that it therefore should be placed in its own genus. 
Since such a genus had never before been named and described, it was
up to Baldwin to do so.  He took the opportunity to name his new
genus
<i>Constancea</i> B. G. Baldwin, in honor of the late Professor
Emeritus Lincoln Constance, world-renowned plant systematist (Ertter,
2001), who had not only studied
<i>Eriophyllum</i> as a dissertation topic
(under Willis Linn Jepson), but recognized
<i>E. nevinii</i>
as a
particularly distinct species even then (Constance, 1937).		</td>
