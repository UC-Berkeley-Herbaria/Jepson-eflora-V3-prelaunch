Many
of the entries in ICPN for names that may or may not represent
changes relative to those used in <i>The Jepson Manual</i> have elicited
contributions from users of the Jepson Online Interchange, including
but not limited to the specialists who contribute taxonomic
treatments of the plant groups involved.  These appear under
&ldquo;Correspondence and Comments Subsequent to Initial Analysis&rdquo;
as
&ldquo;Correspondence.&rdquo;
Each
&ldquo;Correspondence&rdquo;
is given sequentially a number
(e.g., Correspondence 1), the date and contributor are indicated, the
comments are stored in the database but not actually displayed, and
the Editor provides
&ldquo;Editorial Comments&rdquo;
with the same number (e.g.,
Editorial Comments 1).  Such
&ldquo;Editorial Comments&rdquo;
include summary and
paraphrasing of the contribution, as well as a statement about the
effects that the information has or might have on the
&ldquo;Editorial Summary and Current Status,&rdquo;
