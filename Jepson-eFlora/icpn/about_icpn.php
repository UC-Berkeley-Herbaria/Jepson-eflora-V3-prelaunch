Whereas
&ldquo;Editorial Summary&rdquo;
includes a statement of the status of a name
relative to <i>The Jepson Manual</i>,
&ldquo;Current Status&rdquo;
is a statement of the status of a name relative to the flora of
California as we understand it currently, a more absolute concept;
the two are not equal.  For example, names with an
&ldquo;Editorial Summary&rdquo;
that reads &quot;addition, for taxon described since TJM&quot; and one that
reads &quot;addition, in different genus since TJM&quot; may both have a
&ldquo;Current Status&rdquo;
category of  JFP-1, accepted name for taxon native to CA. 
Conversely, names with the same
&ldquo;Editorial Summary&rdquo;
statements (e.g.,
&quot;addition, in different genus since TJM&quot;) may have different
&ldquo;Current Status&rdquo;
categories (e.g., for
<a href="/cgi-bin/get_cpn.pl?Tetraneuris+acaulis&expand=1">
<i>Tetraneuris acaulis</i>
(Pursh) Greene,</a>
JFP-1, accepted name for taxon native to CA, or, for
<a href="/cgi-bin/get_cpn.pl?Pericallis+hybrida&expand=1">
<i>Pericallis hybrida</i>
B. Nord,</a>
JFP-2, accepted name for taxon naturalized in CA).		</td>
