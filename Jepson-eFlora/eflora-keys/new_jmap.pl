              $map = newFromGif GD::Image(GIF) || die "Cant open basemap\n";
              close GIF;

       use CGI;                             # load CGI routines
       $q = new CGI;                        # create new CGI object


$nullvec="";
for $i (0 .. 39){
vec($nullvec,$i,1) = 0;
}
while(<DATA>){
#print;
chomp;
($region,$mapcoord, $mapcolor,$longregion,$province) = split(/\t/, $_);
$prov{$region}=$sort_order++;
$parent{$region}=$province;
$expand{$region}=$longregion;
push(@regions,$region);
#hash with colors associated with region
$colors{$region} = $mapcolor;
#hash withcoordinates associated with region
$coord{$region} = $mapcoord;
}
#this sort is important, since it establishes the order of the bit vector,
#which should have been generated following a similar sort
#make sure here's not a blank line at data's end
foreach (@regions){
if(m/^([a-z])(.*)/){
$sortstring{$_} = "$2$1";
$sortstring{$_} =~ s/c$/o/;
}
else{
$sortstring{$_} = $_;
}
}
@regions=sort bycaps (@regions);
sub bycaps {
$sortstring{$a} cmp $sortstring{$b} ||
$a cmp $b
}
#Query string will replace this file read
undef(%prov_seen);
if($ENV{'QUERY_STRING'} =~/^..........$/){
$hc=$ENV{'QUERY_STRING'};
}
if($ENV{'QUERY_STRING'}=~/^(..........).*credit=.*/){
$hc=$1;
$credit="Map generated by Jepson eFlora, University and Jepson Herbaria";
}
if($ENV{'QUERY_STRING'}=~/^(..........).*no_legend=1/){
$hc=$1;
$no_legend=1;
}
$distvec = $nullvec;
	#translate hex code to bit vector
#warn unpack("b*",pack("H*",$hcode)), "\n";
$distvec = pack("b*", unpack("b*",pack("H*",$hc)));
 $white = $map->colorClosest(255,255,255); # find white
$black = $map->colorClosest(0,0,0); # find black
$red = $map->colorAllocate(255,0,0); # find red
$bodycolor = $map->colorAllocate(244,250,255);
$map->fill(400,100,$bodycolor);

$map->string(gdLargeFont,10,428,"$credit",$black);

$keyx=170;
$keyy=0;
$keyw=20;
$keyh=10;
$keystr=$keyw+5;
foreach $r (sort {$prov{$regions[$a]} <=> $prov{$regions[$b]}}(0 .. 34)){
if(vec($distvec,$r,1)){
#only allocate the colors if you need them
unless($prov_seen{$parent{$regions[$r]}}++){
unless($no_legend){
$map->string(gdSmallFont,$keyx,$keyy,"$parent{$regions[$r]}",$red);
}
$keyy+=15;
}
$regioncolor = $map->colorAllocate(split(/,/,$colors{$regions[$r]})) ;
unless($no_legend){
$map->filledRectangle($keyx,$keyy,$keyx+$keyw,$keyy+$keyh,$regioncolor);
$map->string(gdSmallFont,$keyx+$keystr,$keyy,"$expand{$regions[$r]}",$black);
}
$keyy+=15;
if($keyy >160 && $keyx==170){
#$keyx=445; $keyy=5;
$keyx=370; $keyy=5;
}
#warn "$r:$coord{$regions[$r]}\n";


if($regions[$r] =~ /DMtns/){
$map->fill(234,273,$regioncolor);
$map->fill(234,223,$regioncolor);
$map->fill(244,244,$regioncolor);
$map->fill(234,259,$regioncolor);
$map->fill(256,272,$regioncolor);
$map->fill(288,365,$regioncolor);
$map->fill(319,310,$regioncolor);
$map->fill(238,239,$regioncolor);
$map->fill(328,340,$regioncolor);
}
elsif($regions[$r] =~ /ChI/){
	if($regions[$r] =~ /nChI/){
$map->fill(151,369,$regioncolor);
$map->fill(162,367,$regioncolor);
}
elsif($regions[$r] =~ /sChI/){
$map->fill(212,395,$regioncolor);
$map->fill(210,416,$regioncolor);
}
}
elsif($regions[$r] =~ /SCoRI/){
$map->fill(117,252,$regioncolor);
#$map->fill(145,300,$regioncolor);
$map->fill(158,320,$regioncolor);
$map->fill(161,309,$regioncolor);
}
elsif($regions[$r] =~ /SNE/){
$map->fill(205,215,$regioncolor);
$map->fill(226,216,$regioncolor);
}
elsif($regions[$r] =~ /SnFrB/){
$map->fill(103,231,$regioncolor);
$map->fill(61,184,$regioncolor);
}
elsif($regions[$r] =~ /NCo$/){
$map->fill(12,81,$regioncolor);
$map->fill(30,151,$regioncolor);
}
elsif($regions[$r] =~ /CCo/){
$map->fill(94,250,$regioncolor);
$map->fill(134,326,$regioncolor);
}
else {
$map->fill(split(/,/,$coord{$regions[$r]}), $regioncolor);
}



}
}



       print $q->header(-type=>'image/gif',-expires=>'+3d');
binmode(STDOUT);
print STDOUT $map->gif;
close (STDOUT);

