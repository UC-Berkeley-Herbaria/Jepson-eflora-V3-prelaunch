<div class=pageMajorHeading>Collaborative Effort Produces Jepson Manual Geographic Subdivision Boundary Revisions for the Klamath and Cascade Ranges of northwestern California.
</div><div class=bodyText><i>By Julie Kierstead Nelson and Len Lindstrand III</i></div>
<br>

<p class=bodyText>On the way to nowhere, in the epicenter of poison-oakiness, steep and rocky, with blast furnace heat in summer and torrential rains in winter; it’s no wonder the southeastern Klamath Ranges (KR) remain a mystery landscape explored by very few botanists. This is the area visited by John O. Sawyer’s “Off the Beaten Path in the Shasta-Trinity National Recreation Area” Jepson workshop in May of 2008; the oldest part of the Klamath Ranges.</p>
<p class=bodyText>When the 1993 <i>Jepson Manual</i> was published, its map of Geographic Subdivisions of California drew the KR boundary to exclude this landscape, including it in the adjacent Cascade Ranges (CaR). At its eastern boundary the predominantly metamorphic KR meets the volcanic Cascade Range (CaR) in an area roughly interpreted by the 1993 Jepson map as the Interstate 5 corridor north of Redding, following the upper Sacramento River canyon. This interpretation omits most of the southeastern Klamath Ranges, a significant portion of the KR unique in its own right, and incorrectly includes the area in CaR, resulting in large areas of limestone and metasedimentary geology being placed in CaR, which is inconsistent with the Jepson description for that volcanic region. </p>
<p class=bodyText>One outcome of the original KR/CaR boundary that is problematic results when conducting floristic analysis in this area; for example, <i>Ageratina shastensis</i>, a rare KR endemic of limestone and metasedimentary rock outcrops, has its range described in the second edition of <i>The Jepson Manual</i> (TJM2) as “CaR” because of the misinterpreted KR boundary. Other KR endemics, such as Arnica venosa, are currently described in TJM2 as occurring both in KR and CaR. </p>
<p class=bodyText>It’s certainly understandable that the KR region was not interpreted to extend so far east. While relatively near population centers and major transportation corridors, this area is functionally very remote and characterized by steep terrain, intense summer heat, and miles of poison oak. Besides recreation at Shasta Lake, this area receives little visitation and has largely been underexplored botanically for years. </p>
<p class=bodyText>Why change the boundary now?  Several large federal agency projects in this area in the last two decades have produced an abundance of new plant distribution and ecological data. Additionally, digitized Consortium of California Herbaria (CCH) records with coordinates now make floristic analysis much more feasible, and several new southeastern KR endemic species have been recently described or are in process. The time seemed right to make much-needed changes to the KR boundary.</p>
<p class=bodyText>Since early 2014, a team has worked together to address this issue and improve the Jepson map by revising the KR and CaR boundaries to better align with current scientific consensus about the extents of these geographic subdivisions and published geology, soils, and vegetation maps. This team includes Jepson staff and associates Staci Markos, David Baxter, Heath Bartosh, and three botanists familiar with the geography and flora of the area: Shasta-Trinity National Forest Botanist Julie Kierstead Nelson, Len Lindstrand III of North State Resources Inc., and botanical consultant Dean W. Taylor. </p>
<p class=bodyText>Our team started with our collective experience and existing ecological subregion and geology maps to identify the “disputed area” requiring boundary revisions. Then we took a hard look at the taxa documented from the disputed area to see if they merited geographic range updates based on the new geographic subdivision boundaries. Using CCH records to identify these taxa, Jepson staff developed a list of over 230 species for review. We reviewed each taxon to identify those occurring in the KR, those that occur in both KR and CaR, and those that don’t occur in KR, and submitted the results for appropriate updating. Meanwhile, Jepson associate Heath Bartosh created a new KR GIS boundary with our input. Following the boundary change, we updated the existing Jepson geographic subdivision descriptions for KR and CaR to reflect the boundary revisions. Following review and acceptance by the Jepson Curator, Bruce Baldwin, we declared victory!  The result is more accurate KR and CaR boundaries, including the CaRF and CaRH geographic subdivisions, updated geographic division descriptions, and updated range descriptions for selected taxa occurring in this area. </p>
<p class=bodyText>The new KR boundary now encompasses most of the lands east of Interstate 5, south of Highway 89, and north of Highway 299E to include Shasta Lake, the McCloud and Hosselkus limestone formations, and Grizzly Peak. The new CaR boundary now starts entirely east of Shasta Lake, and abuts the Inner North Coast Ranges subregion along Interstate 5 from west of Redding south to Red Bluff. </p>
<p class=bodyText>Our newly drawn boundary and analysis of CCH specimens have also shown clearly that the flora of the southeastern KR has more affinity with the Sierra Nevada than with the intervening CaR; but that is a story for another day.</p>

