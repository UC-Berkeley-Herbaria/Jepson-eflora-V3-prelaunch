            <h1>Jepson eFlora Revision Summary</h1>

<p>The Jepson eFlora is revised annually to include substantive taxonomic changes (e.g., taxa added or deleted). Revisions are posted online in March and are informed by the most recent scientific evidence. Strictly nomenclatural changes and other small changes are made as errata throughout the year. Click here to see a full list of Jepson eFlora errata changes. 
</p>
<p>The treatments in the Jepson eFlora supersede those in the second edition of <em>The Jepson Manual</em> (2012). 
</p>
            <div class="citation" style="margin: 20px 0;">

<p>A summary of Revisions 1-14 is presented below (by year).<br>

