<span class="pageMajorHeading">About the <i>Jepson eFlora</i></span>
<br><br>
<p class="bodyText">Treatments and keys in the <em>Jepson eFlora</em> were initially derived from <I>The Jepson Manual: Vascular Plants of California, Second Edition</I> (TJM2), available from <a href="http://www.ucpress.edu/book.php?isbn=9780520253124">University of California Press</a>.
</p>
<span class="bodyText">
<P>
  The eFlora expands on the content of TJM2, including descriptions of taxa not included in the print book (e.g. waifs, agricultural weeds), substantive revisions of scientific content for some taxa, and many errata and other small changes made relative to the print book.
  <ul>
  <li>Summary of <a href="/IJM_suppl_summary.html">Revision 1 (2013)</a>, <a href="/IJM_suppl_summary.html#rev2">Revision 2 (2014)</a> and <a href="/IJM_suppl_summary.html#rev3">Revision 3 (2015)</a>, including downloadable supplements for TJM2</li>
  <li><a href="http://ucjeps.berkeley.edu/JM12_errata.html">List of all errata and other small changes</a></li>
  </ul>
  
