<p><span class="pageMajorHeading">About the <i>Jepson eFlora</i></span></p>
<br />
<p class="bodyText">Treatments and keys in the <em>Jepson eFlora</em> were initially derived from <I>The Jepson Manual: Vascular Plants of California, Second Edition</I> (TJM2), available from <a href="https://www.ucpress.edu/book/9780520253124/the-jepson-manual">University of California Press</a>.  <!--old link For an explanation of conventions applying to the printed <i>Manual</i>, click here: <a href="http://ucjeps.berkeley.edu/IJM_conventions.html" class="tocLink" >User's Guide</a>-->
</p>
<!--old link  <a href="http://www.ucpress.edu/book.php?isbn=9780520253124">-->

<p><span class="bodyText">The eFlora expands on the content of TJM2, including descriptions of taxa not included in the print book (e.g. waifs, agricultural weeds), substantive revisions of scientific content for some taxa, and many errata and other small changes made relative to the print book.</span></p>
