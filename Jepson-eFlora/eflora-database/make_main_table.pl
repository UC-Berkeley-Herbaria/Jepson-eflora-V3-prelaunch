    # We capture the content inside the parentheses starting with 'Group'
    if ($par =~ /^(?:COMMON NAME|TAXON AUTHOR):\s*.*?\s*\((Group[^)]*)\)/m) {
        my $group = $1;

        # 2. Escape single quotes for SQL safety
        $group =~ s/'/''/g;
        return "'$group'";
    }

    return "NULL";
}

