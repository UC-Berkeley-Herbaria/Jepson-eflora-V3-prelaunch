# --- Setup / Helpers ---
sub unquote {
    my $s = shift // '';
    $s =~ s/^'|'$//g;
    return $s eq 'NULL' ? '' : $s;
}

sub format_for_SQL {
    my ($input) = @_;

    # 1. If the value is undefined, return literal NULL
    return "NULL" if !defined $input;

    # 2. Escape any existing single quotes by doubling them (SQL standard)
    #$input =~ s/'/''/g;

    # 3. Return the quoted string
    return "'$input'";
}

sub basic_get {
    my ($paragraph, $tag) = @_;
    my ($match) = $paragraph =~ /\Q$tag\E:\s*(.*)/;
    
    return defined $match ? "'$match'" : "NULL";
}



sub get_field {
    my ($par, $tag) = @_;
    if ($par =~ /^\Q$tag\E:\s*(.+)/m) {
        my $val = $1;
        $val =~ s/^\s+|\s+$//g;
        $val =~ s/'/''/g;
        return "'$val'";
    }
    return "NULL";
