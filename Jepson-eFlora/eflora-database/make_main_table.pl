sub format_for_SQLite {
	#given exactly one variable
	#if the variable has contents, put single quotes around the string
	#else, return "NULL" without quotes
	my ($input) = @_;
	if ($input){
		return "'".$input."'";
	}
	else {
		return "NULL";
	}
}

sub basic_get {
