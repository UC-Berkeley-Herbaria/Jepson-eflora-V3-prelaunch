        	return "'3,4,5,6'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(Apr\)May--Jun\(Aug\)\n/){
        	return "'3,4,5,6'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(Apr\)Jun--Aug\(Sep\)\n/){
        	return "'3,5,6,7,8'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(Apr\)Jun--Aug\(Dec\)\n/){
        	return "'3,5,6,7,11'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(May\)Jun--Aug\(Sep\)\n/){
        	return "'4,5,6,7,8'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(May\)Jun--Jul\(Sep\)\n/){
        	return "'4,5,6,8'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(May\)Jul--Aug\(Oct\)\n/){
        	return "'4,6,7,'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\(Feb,Apr\)Jun--Aug\n/){
        	return "'1,3,5,6,7'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *\+?-? *[Ss]ummer\n/){
        	return "'5,6,7'"; 
		}
		elsif($entry =~ /FLOWERING TIME: *Spring\n/){
        	return "'2,3,4'"; 
		}
#single month flowering times are rare, but present.  This part fixes the original code which ignored single month dates
		elsif($entry =~ /FLOWERING TIME: *(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\n/){
			$no = $MONTH_MAP{$1};
        	return "'".$no."'"; 
		}
#there are other variants being missed by this script.  they need to be added here
        else{
            if($entry =~ m/FLOWERING TIME:(.+)/){
            	print "MISSING TIME CODE-->".$1."\n".$_."\n\n";
            }
            return "NULL";
        }
}

