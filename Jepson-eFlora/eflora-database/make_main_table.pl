sub basic_get {
    my ($paragraph, $tag) = @_;
    
    # \b ensures that $tag must be a distinct word.
    # It prevents "CONES" from matching inside "POLLEN CONES" or "SEED CONES".
    if ($paragraph =~ /\b$tag:\s*(.*)/) {
        my $val = $1;
        $val =~ s/\s+$//; # trim trailing whitespace
        return "'" . $val . "'";
    } else {
        return "NULL";
    }
}

